export type Channel='chat'|'call'|'whatsapp';
export type Participant={id:string;role:'buyer'|'seller';phoneVerified:boolean};
export type Risk='clear'|'warn'|'held';
export type Message={id:string;conversationId:string;senderId:string;kind:'text'|'image';text:string;attachmentId?:string;
  risk:Risk;riskReasons:string[];createdAt:string};
export type Conversation={id:string;listingId:string;buyerId:string;sellerId:string;createdAt:string;updatedAt:string;
  blockedBy:string[];lastSellerOpenedAt?:string};
export type Lead={id:string;listingId:string;buyerId:string;sellerId:string;channel:Channel;conversationId?:string;at:string};
export type Report={id:string;conversationId:string;reporterId:string;reason:'scam'|'abuse'|'spam'|'other';note:string;createdAt:string};
export type Notification={id:string;conversationId:string;recipientId:string;channel:'push'|'sms'|'email';
  status:'queued'|'sent'|'failed';createdAt:string};
export type Attachment={id:string;conversationId:string;uploaderId:string;privateKey:string;mimeType:'image/webp';createdAt:string};
export type MessagingState={conversations:Conversation[];messages:Message[];leads:Lead[];reports:Report[];
  notifications:Notification[];attachments:Attachment[]};
export type MessagingStore={read():Promise<MessagingState>;transaction<T>(fn:(state:MessagingState)=>T):Promise<T>};
export type AlertTarget={pushToken?:string;phone?:string;email?:string;pushEnabled:boolean;smsOptIn:boolean;emailOptIn:boolean};
export type AlertPort={target(sellerId:string):Promise<AlertTarget|undefined>;
  push?(token:string,body:string):Promise<void>;sms?(phone:string,body:string):Promise<void>;email?(address:string,body:string):Promise<void>};
export type BotCheckPort={verify(participant:Participant,proof:string,action:'message'|'contact'|'reveal'):Promise<boolean>};
