const bengaliDigits = "০১২৩৪৫৬৭৮৯"
export function localizeDigits(value: string, language: BangladeshLanguage) {
  if (language === "en") return value
  return value.replace(/[0-9]+/g, (digits, offset: number) => {
    // Keep model codes such as A15 and 20Xi in their official spelling.
    if (/[A-Za-z]/.test(value[offset - 1] || "") ||
      /[A-Za-z]/.test(value[offset + digits.length] || "")) return digits
    return digits.replace(/[0-9]/g, digit => bengaliDigits[Number(digit)])
  })
}

