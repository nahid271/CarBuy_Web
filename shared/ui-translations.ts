export function translateUiText(input: string, language: BangladeshLanguage): string {
  if (language === "en" || !input.trim()) return input
  const leading = input.match(/^\s*/u)?.[0] || ""
  const trailing = input.match(/\s*$/u)?.[0] || ""
  const core = input.trim().replace(/\s+/gu, " ")
  const direct = banglaUi[core]
  const patterned = direct || patterns.map(rule => {
    const match = core.match(rule.match)
    return match ? rule.render(match) : null
  }).find(Boolean)
  const localized = (patterned || core).replace(/\blakh\b/g, "লাখ").replace(/\bkm\b/g, "কিমি")
  return leading + localizeDigits(localized, language) + trailing
}
